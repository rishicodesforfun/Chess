import torch
from torch.utils.data import Dataset
import json
import numpy as np
import glob

def fen_to_tensor(fen_history, move_count, halfmove_clock):
    """
    Converts a history of FEN strings to a 119x8x8 tensor.
    fen_history: list of FEN strings, latest first.
    """
    tensor = np.zeros((119, 8, 8), dtype=np.float32)
    
    # Fill history planes (12 planes * 8 positions = 96 planes)
    for h in range(min(8, len(fen_history))):
        fen = fen_history[h]
        parts = fen.split()
        board_part = parts[0]
        
        piece_map = {'P': 0, 'N': 1, 'B': 2, 'R': 3, 'Q': 4, 'K': 5,
                     'p': 6, 'n': 7, 'b': 8, 'r': 9, 'q': 10, 'k': 11}
        
        rank = 7
        file = 0
        for char in board_part:
            if char == '/':
                rank -= 1
                file = 0
            elif char.isdigit():
                file += int(char)
            else:
                plane = h * 12 + piece_map[char]
                tensor[plane, rank, file] = 1.0
                file += 1
                
    # Constant planes (112-118)
    last_fen = fen_history[0]
    parts = last_fen.split()
    
    # 112: Side to move
    if parts[1] == 'w':
        tensor[112, :, :] = 1.0
        
    # 113: Total move count
    tensor[113, :, :] = float(move_count) / 100.0
    
    # 114-117: Castling rights
    if len(parts) > 2:
        castling = parts[2]
        if 'K' in castling: tensor[114, :, :] = 1.0
        if 'Q' in castling: tensor[115, :, :] = 1.0
        if 'k' in castling: tensor[116, :, :] = 1.0
        if 'q' in castling: tensor[117, :, :] = 1.0
        
    # 118: No-progress count
    tensor[118, :, :] = float(halfmove_clock) / 100.0
        
    return tensor

class ChessGameDataset(Dataset):
    """
    Loads training data from the self-play JSONL files generated by the C++ engine.
    """
    def __init__(self, jsonl_pattern):
        self.positions = []
        self.move_targets = []
        self.value_targets = []
        
        for filename in glob.glob(jsonl_pattern):
            self._load_games(filename)
    
    def _load_games(self, filename):
        with open(filename, 'r') as f:
            for line in f:
                if not line.strip(): continue
                game = json.loads(line)
                outcome = game['outcome']
                
                # Each game has a list of FENs and the move played at that FEN
                for i in range(len(game['moves'])):
                    # Get up to 8 previous FENs
                    history_start = max(0, i - 7)
                    fen_history = game['fens'][history_start:i+1]
                    fen_history.reverse() # latest first
                    
                    # Extract move count and halfmove clock from latest FEN
                    last_parts = game['fens'][i].split()
                    halfmove = int(last_parts[4]) if len(last_parts) > 4 else 0
                    fullmove = int(last_parts[5]) if len(last_parts) > 5 else 1
                    
                    move = game['moves'][i]
                    
                    pos_tensor = fen_to_tensor(fen_history, fullmove, halfmove)
                    self.positions.append(pos_tensor)
                    self.move_targets.append(move)
                    self.value_targets.append(outcome)
    
    def __len__(self):
        return len(self.positions)
    
    def __getitem__(self, idx):
        pos_tensor = torch.from_numpy(self.positions[idx])
        move_target = torch.tensor(self.move_targets[idx], dtype=torch.long)
        value_target = torch.tensor(self.value_targets[idx], dtype=torch.float32)
        
        return pos_tensor, move_target, value_target
