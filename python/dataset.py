import torch
from torch.utils.data import Dataset
import json
import numpy as np
import glob

class ChessGameDataset(Dataset):
    """
    Loads training data from the self-play JSONL files generated by the C++ engine.
    """
    def __init__(self, jsonl_pattern):
        self.positions = []
        self.move_targets = []
        self.value_targets = []
        
        for filename in glob.glob(jsonl_pattern):
            self._load_games(filename)
    
    def _load_games(self, filename):
        with open(filename, 'r') as f:
            for line in f:
                if not line.strip(): continue
                game = json.loads(line)
                outcome = game['outcome']
                
                # For this implementation, we map the game moves directly.
                # In a full system, we parse game['fens'] into 119-plane tensors.
                # Here we supply zero-tensors of the correct shape as placeholders 
                # so the training loop can be tested.
                for move in game['moves']:
                    pos_tensor = np.zeros((119, 8, 8), dtype=np.float32)
                    self.positions.append(pos_tensor)
                    self.move_targets.append(move)
                    self.value_targets.append(outcome)
    
    def __len__(self):
        return len(self.positions)
    
    def __getitem__(self, idx):
        pos_tensor = torch.from_numpy(self.positions[idx])
        move_target = torch.tensor(self.move_targets[idx], dtype=torch.long)
        value_target = torch.tensor(self.value_targets[idx], dtype=torch.float32)
        
        return pos_tensor, move_target, value_target
